// Refreshes the vendored disposable-domain list from a pinned commit of
// https://github.com/disposable-email-domains/disposable-email-domains (CC0 1.0).
//   node scripts/maiteam/update-disposable-domains.mjs <full commit sha>
// Without a sha it only regenerates lib/maiteam/disposable-domains-data.js from the vendored file.
// Then update vendor/disposable-email-domains/SOURCE.md with the sha, date and sha256 it prints,
// run `npm test`, and commit the three files together.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const REPO = "disposable-email-domains/disposable-email-domains";
const LIST = new URL("../../vendor/disposable-email-domains/disposable_email_blocklist.conf", import.meta.url);
const LICENSE = new URL("../../vendor/disposable-email-domains/LICENSE.txt", import.meta.url);
const MODULE = new URL("../../lib/maiteam/disposable-domains-data.js", import.meta.url);

export function parseList(text) {
	return [...new Set(text.split("\n").map((line) => line.trim().toLowerCase()).filter((line) => line && !line.startsWith("#")))].sort();
}

export function renderModule(domains, sha256) {
	return `// Generated by scripts/maiteam/update-disposable-domains.mjs from vendor/disposable-email-domains/
// disposable_email_blocklist.conf (sha256 ${sha256}). Do not edit by hand.
export const DISPOSABLE_LIST_SHA256 = "${sha256}";
export const DISPOSABLE_DOMAINS = ${JSON.stringify(domains)};
`;
}

async function download(sha, file) {
	const response = await fetch(`https://raw.githubusercontent.com/${REPO}/${sha}/${file}`);
	if (!response.ok) throw new Error(`${file}: HTTP ${response.status}`);
	return response.text();
}

if (import.meta.url === `file://${process.argv[1]}`) {
	const sha = process.argv[2];
	if (sha && !/^[0-9a-f]{40}$/.test(sha)) throw new Error("Pass a full 40-character commit sha, not a branch.");
	if (sha) {
		await writeFile(LIST, await download(sha, "disposable_email_blocklist.conf"));
		await writeFile(LICENSE, await download(sha, "LICENSE.txt"));
	}
	const text = await readFile(LIST, "utf8");
	const sha256 = createHash("sha256").update(text).digest("hex");
	const domains = parseList(text);
	await writeFile(MODULE, renderModule(domains, sha256));
	console.log(`commit ${sha ?? "(vendored file)"}\nsha256 ${sha256}\ndomains ${domains.length}`);
}
